using System.Globalization;
using System.Runtime.CompilerServices;
using UeBar.Core.Localization;

namespace UeBar.Modules.HomeAssistant.Tests;

/// <summary>
/// Many tests check German UI texts and German number formats. Pin the culture to de-DE so they
/// behave the same on every machine (R1); language switching itself has its own tests.
/// </summary>
internal static class TestCulture
{
#pragma warning disable CA2255 // module initializer in a test assembly is intended
    [ModuleInitializer]
#pragma warning restore CA2255
    internal static void PinGerman()
    {
        var german = CultureInfo.GetCultureInfo("de-DE");
        CultureInfo.DefaultThreadCurrentCulture = german;
        CultureInfo.DefaultThreadCurrentUICulture = german;
        CultureInfo.CurrentCulture = german;
        CultureInfo.CurrentUICulture = german;
        UiCultureSource.Shared.Set(german);
    }
}
